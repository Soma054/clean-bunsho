import AppKit
import CleanBunshoCore

enum PasteboardCleaner {
    /// パスワード管理アプリなどが付ける「秘密情報」「一時的」の印（nspasteboard.org の取り決め）
    static let sensitiveTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    static func isSensitive(_ pb: NSPasteboard = .general) -> Bool {
        guard let types = pb.types else { return false }
        return types.contains { sensitiveTypes.contains($0) }
    }

    /// ファイルや画像のコピーは文字として扱わない（書き換えるとファイルの貼り付けが壊れるため）
    static func holdsNonTextContent(_ pb: NSPasteboard = .general) -> Bool {
        guard let types = pb.types else { return false }
        return types.contains(.fileURL) || types.contains(.tiff) || types.contains(.png)
    }

    /// クリップボードの文字をきれいにする。
    /// 何も変わらなかったときは書き換えない（書式を壊さないため）。文字がなければ nil
    @discardableResult
    static func clean(_ pb: NSPasteboard = .general, options: CleanOptions) -> CleanResult? {
        guard !holdsNonTextContent(pb), let text = pb.string(forType: .string) else { return nil }
        let result = Cleaner.clean(text, options: options)
        if result.changed {
            pb.clearContents()
            pb.setString(result.text, forType: .string)
        }
        return result
    }
}

/// クリップボードの変化を見張る（0.5秒ごとに changeCount を確認）
@MainActor
final class ClipboardMonitor {
    var onChange: (() -> Void)?
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// 自分で書き換えた変化は無視する
    func markOwnWrite() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func tick() {
        let count = NSPasteboard.general.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        onChange?()
    }
}
